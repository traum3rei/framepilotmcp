import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tsxCli = join(root, 'node_modules', 'tsx', 'dist', 'cli.mjs');
if (!existsSync(tsxCli)) {
  console.error('tsx ist noch nicht installiert. Bitte zuerst npm install ausführen.');
  process.exit(1);
}
const blender = process.env.BLENDER_PATH || (process.platform === 'darwin'
  ? '/Applications/Blender.app/Contents/MacOS/Blender' : 'blender');
const scene = resolve(process.env.FRAMEPILOT_SCENE || join(root, 'scene.blend'));
const config = [
  '# Generated by npm run setup:codex (machine-local absolute paths)',
  '[mcp_servers.framepilot]',
  `command = ${JSON.stringify(process.execPath)}`,
  `args = [${JSON.stringify(tsxCli)}, ${JSON.stringify(join(root, 'src', 'server.ts'))}]`,
  `cwd = ${JSON.stringify(root)}`,
  'startup_timeout_sec = 20',
  'tool_timeout_sec = 210',
  '',
  '[mcp_servers.framepilot.env]',
  `BLENDER_PATH = ${JSON.stringify(blender)}`,
  `FRAMEPILOT_SCENE = ${JSON.stringify(scene)}`,
  '',
].join('\n');
mkdirSync(join(root, '.codex'), { recursive: true });
const output = join(root, '.codex', 'config.toml');
if (existsSync(output)) {
  console.error(`Konfiguration existiert bereits: ${output}`);
  console.error('Nicht überschrieben. Entferne die Datei zuerst oder passe sie manuell an.');
  process.exit(1);
}
writeFileSync(output, config);
console.log(`Codex-MCP-Konfiguration erstellt: ${output}`);
console.log('Öffne den FramePilot-Ordner mit lokalem Codex (CLI oder IDE). Vertraue dem Projekt, damit .codex/config.toml geladen wird.');
console.log('In Codex CLI: /mcp. Überprüfe, ob framepilot und die drei Tools angezeigt werden.');
